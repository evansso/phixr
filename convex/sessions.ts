import { v } from "convex/values";
import type { Id } from "./_generated/dataModel";
import { mutation, query } from "./_generated/server";

async function requireUserId(ctx: {
	auth: { getUserIdentity: () => Promise<{ subject: string } | null> };
}) {
	const identity = await ctx.auth.getUserIdentity();
	if (!identity) {
		throw new Error("Unauthenticated");
	}
	return identity.subject;
}

export const getTitle = query({
	args: { sessionId: v.id("sessions") },
	handler: async (ctx, { sessionId }) => {
		const userId = await requireUserId(ctx);
		const session = await ctx.db.get(sessionId);
		if (!session || session.userId !== userId) {
			return null;
		}
		return { title: session.title, status: session.status };
	},
});

export const list = query({
	args: {},
	handler: async (ctx) => {
		const userId = await requireUserId(ctx);
		const sessions = await ctx.db
			.query("sessions")
			.withIndex("by_user_updated", (q) => q.eq("userId", userId))
			.order("desc")
			.collect();
		return sessions.map(({ _id, chatKey, title, status, createdAt, updatedAt }) => ({
			_id,
			chatId: chatKey ?? _id,
			title,
			status,
			createdAt,
			updatedAt,
		}));
	},
});

export const create = mutation({
	args: { title: v.string() },
	handler: async (ctx, { title }) => {
		const userId = await requireUserId(ctx);
		const now = Date.now();
		return await ctx.db.insert("sessions", {
			userId,
			title,
			status: "active",
			createdAt: now,
			updatedAt: now,
		});
	},
});

export const getOrCreate = mutation({
	args: { chatKey: v.string() },
	handler: async (ctx, { chatKey }) => {
		const userId = await requireUserId(ctx);
		const byChatKey = await ctx.db
			.query("sessions")
			.withIndex("by_chat_key", (q) => q.eq("chatKey", chatKey))
			.first();
		if (byChatKey) {
			if (byChatKey.userId !== userId) throw new Error("Session not found");
			return byChatKey._id;
		}

		let byId;
		try {
			byId = await ctx.db.get(chatKey as Id<"sessions">);
		} catch {
			// New chats use the temporary ID generated by useChat, not a Convex ID.
		}
		if (byId) {
			if (byId.userId !== userId) throw new Error("Session not found");
			return byId._id;
		}

		const now = Date.now();
		return await ctx.db.insert("sessions", {
			userId,
			chatKey,
			title: "New chat",
			status: "active",
			createdAt: now,
			updatedAt: now,
		});
	},
});

export const update = mutation({
	args: {
		sessionId: v.id("sessions"),
		title: v.optional(v.string()),
		status: v.optional(
			v.union(v.literal("active"), v.literal("resolved"), v.literal("archived"))
		),
	},
	handler: async (ctx, { sessionId, ...updates }) => {
		const userId = await requireUserId(ctx);
		const session = await ctx.db.get(sessionId);
		if (!session || session.userId !== userId) {
			throw new Error("Session not found");
		}
		await ctx.db.patch(sessionId, { ...updates, updatedAt: Date.now() });
	},
});
